"""B07 配置常量

本阶段（B07 S1）只做时间锚点与证据采集，不接天气、不接知识库、不接摄像头。

S5-1 增加了一个**降级开关**（唯一的实验开关）：

    B07_WEATHER_UNAVAILABLE=1

  未设置（默认）：一切照常，天气照常取数。
  设为 "1"    ：天气 provider 直接返回"不可用"结果
                （status=unavailable、data=None、error 写明原因），
                模拟"天气 API 暂时不可用"。

  用途：S5 的证据退化实验 —— 一次只弄坏一条证据（这一轮是天气），
        看系统还剩什么能判断、什么不能判断。
        开关的判定逻辑只有一处：B07.weather.weather_unavailable_reason()。
        详见 B07/weather.py 顶部的说明。

  注意：这是**显式模拟**，不是真的断网 —— 断网不可复现，
        也会把"天气不可用"和"整个网络坏了"混在一起。
"""

import os
from datetime import timedelta

# --------------------------------------------------------------------------
# 位置 / 时间锚点
# --------------------------------------------------------------------------
DEFAULT_LOCATION = "A区-3号温室"

# --------------------------------------------------------------------------
# 历史窗口规格
# --------------------------------------------------------------------------
HISTORY_POINTS = 6                # 历史窗口点数
SAMPLE_INTERVAL_MINUTES = 30      # 采样间隔（分钟）
# 6 点 @30min 的跨度 = 5 个间隔 = 2.5 小时
HISTORY_SPAN = timedelta(hours=2, minutes=30)

# --------------------------------------------------------------------------
# 校验阈值
# --------------------------------------------------------------------------
GAP_WARNING_HOURS = 24.0          # 当前状态与库末点间隔超过此值记 warning


# --------------------------------------------------------------------------
# S5-1 降级开关（唯一的环境变量开关）
# --------------------------------------------------------------------------

#: 环境变量名；值为 "1" 时天气 provider 返回"不可用"
WEATHER_UNAVAILABLE_ENV = "B07_WEATHER_UNAVAILABLE"


def weather_unavailable_requested() -> bool:
    """降级开关是否打开（本文件只读环境变量，判定逻辑的真源在 B07.weather）。

    存在两份读取是刻意的：config.py 是"配置清单"，
    B07.weather 是"判定真源"。这里只回答"开没开"，
    失败原因的文案只在 B07.weather 里写一份。
    """
    return os.environ.get(WEATHER_UNAVAILABLE_ENV, "").strip() == "1"
